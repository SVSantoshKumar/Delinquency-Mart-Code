CREATE OR REPLACE TEMPORARY TABLE DISHA_MART_ANALYTICS.COLLECTION_MART.ch_dedup AS (
    SELECT *
    FROM (
        SELECT
				*,
            ROW_NUMBER() OVER (
                PARTITION BY NEW_LOAN_NO, EXTRACT_DT
                ORDER BY EXTRACT_DT DESC
            ) AS rn
        FROM DISHA_MART_ANALYTICS.COLLECTION_MART.ch_union_raw
