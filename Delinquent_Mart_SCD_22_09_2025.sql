CREATE OR REPLACE TEMPORARY TABLE DISHA_MART_ANALYTICS.COLLECTION_MART.customers_with_mixed_dpd AS
SELECT 
  lad.CUST_ID_FLEX AS CUSTOMER_CODE
FROM DISHA_MART_ANALYTICS.COLLECTION_MART.ld dpd
JOIN DISHA_MART_ANALYTICS.COLLECTION_MART.temp_deduped_cd cd ON dpd.LOAN_NO = cd.LOAN_NO
LEFT JOIN DISHA_L2_CURATED.BASE_MODEL_DATA.LOAN_ACCOUNT_DETAILS lad 
  ON TRIM(CAST(cd.LOAN_NO AS VARCHAR)) = TRIM(lad.LOAN_NO) and lad.activation_flag = 1
WHERE lad.CUST_ID_FLEX IS NOT NULL
GROUP BY lad.CUST_ID_FLEX
HAVING 
  MAX(CASE WHEN dpd.DPD > 0 THEN 1 ELSE 0 END) = 1 AND  MAX(CASE WHEN dpd.DPD = 0 THEN 1 ELSE 0 END) = 1;


CREATE OR REPLACE TEMPORARY TABLE DISHA_MART_ANALYTICS.COLLECTION_MART.current_status_cte AS 
  SELECT 
    cd.LOAN_NO,
    cd.DPD,
    cd.CHEQUE_IN_TRANSIT_COUNT,
    ld.OP_DPD,
	cd.EXTRACTED_DATE,
    CASE 
      WHEN ld.OP_DPD >= 91 AND cd.DPD < 91 AND cd.DPD > 0 THEN ''RTD''
      WHEN cd.DPD = 0 THEN ''NORMAL''
      WHEN  cd.DPD < ld.OP_DPD AND (ld.OP_DPD - cd.DPD) < 30 THEN ''STABLE''
      WHEN cd.DPD < ld.OP_DPD THEN ''ROLLBACK''
      ELSE ''ROLLFORWARD''
    END AS CURRENT_STATUS
  FROM DISHA_MART_ANALYTICS.COLLECTION_MART.temp_deduped_cd cd
LEFT JOIN DISHA_MART_ANALYTICS.COLLECTION_MART.ld ld ON cd.LOAN_NO = ld.LOAN_NO and cd.EXTRACTED_DATE = ld.EXTRACTED_DATE;





