TRIM(CAST(NEW_LOAN_NO AS VARCHAR)) AS NEW_LOAN_NO,
TRIM(CAST(EMP_ID AS VARCHAR)) AS EMP_ID
,COLLECTION_RESPONSIBILITY
,EXECUTIVE_CATEGORY
,TEAM
,CASE WHEN TRIM(TL_EMP_ID) = ''NA'' then '''' end as TL_EMP_ID 
,TL
,TL_NPL
,CASE WHEN TRIM(ACM_EMP_ID) = ''NA'' then '''' end as  ACM_EMP_ID
